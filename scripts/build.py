"""Build the standalone lab and guide using only Python's standard library."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"

def read(name):
    return (SRC / name).read_text(encoding="utf-8")

def page(title, content, *, script="", guide=False):
    styles = read("lab.css") + "\n" + read("site.css")
    nav = ('<a href="index.html">Open lab</a>' if guide else
           '<a href="#rs-views-panel">Feature maps</a><a href="#rs-training-diagnostics">Learning curves</a>')
    heading = "How to use the lab" if guide else "See what changes as a network learns."
    intro = ("A hands-on guide to signals, gradients, and residual connections." if guide else
             "Train a plain network and a residual network on the same landscape. Follow the signals, inspect the weights, and test your own explanations.")
    return f'''<!doctype html>
<!-- Generated by scripts/build.py. Edit src/, then rebuild. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="description" content="An interactive neural network learning lab: compare plain and residual networks, features, weights, gradients, and loss in your browser.">
<title>{title} · Neural Network Learning Lab</title><style>{styles}</style></head>
<body><header class="site-header"><nav aria-label="Main navigation"><a class="brand" href="index.html">NEURAL NETWORK LEARNING LAB</a>{nav}<a href="guide.html" target="_blank" rel="noopener">How to use</a><a href="https://github.com/liuhon33/neural-network-learning-lab" target="_blank" rel="noopener">GitHub ↗</a></nav>
<div class="eyebrow">An open learning experiment by Hongrui Liu</div><h1>{heading}</h1><p class="intro">{intro}</p>
{'' if guide else '<p class="muted">Start with <strong>One update</strong> or <strong>Train 500 updates</strong>. Defaults: 36 blocks × 10 features · Adam 0.003 · seed 7. Runs on your device; reloading resets the experiment.</p>'}</header>
<main{' class="guide"' if guide else ''}>{content}</main>
<footer class="site-footer"><span>MIT licensed · Built for learning by experimentation.</span><a href="guide.html" target="_blank" rel="noopener">Student guide</a><a href="https://github.com/liuhon33/neural-network-learning-lab/blob/main/docs/architecture.md" target="_blank" rel="noopener">How it works</a><a href="https://github.com/liuhon33/neural-network-learning-lab/issues" target="_blank" rel="noopener">Report an issue</a></footer>
{'<script>'+script+'</script>' if script else ''}</body></html>'''

def build():
    script = read("lab.js").replace("/*__ENGINE__*/", read("dense-engine.js")).replace("/*__INSPECTOR__*/", read("inspector.js"))
    assert "/*__ENGINE__*/" not in script and "/*__INSPECTOR__*/" not in script
    for name, output in {
        "index.html": page("Explore", '<noscript>This lab needs JavaScript to train networks and draw the plots.</noscript>' + read("lab.html"), script=script),
        "guide.html": page("Student guide", read("guide.html"), guide=True),
    }.items():
        ids = re.findall(r'\bid="([^"]+)"', output.split("<script>")[0])
        assert len(ids) == len(set(ids)), f"Duplicate HTML ids in {name}"
        (ROOT / name).write_text(output, encoding="utf-8", newline="\n")
        print(f"Built {name} ({len(output.encode('utf-8')):,} bytes)")

if __name__ == "__main__":
    build()
